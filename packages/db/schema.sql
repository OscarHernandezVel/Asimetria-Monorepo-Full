-- Asimetría — esquema de base de datos (PostgreSQL 16 + TimescaleDB).
-- Base: sección "Estructura de las Bases de Datos" del documento Sprint 2. Las columnas marcadas (+) son
-- extensiones necesarias para las vistas de los mockups. Docker lo ejecuta al crear el volumen
-- (docker-entrypoint-initdb.d). La prueba test_modelos_coinciden_con_schema_sql impide que diverja del ORM.
CREATE EXTENSION IF NOT EXISTS timescaledb;

-- 1. usuarios (HU-07)
CREATE TABLE usuarios (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email          VARCHAR(255) NOT NULL UNIQUE,
  password_hash  VARCHAR(255) NOT NULL,                         -- bcrypt, costo >= 12 (RNF-03)
  nombre         VARCHAR(100) NOT NULL,                         -- (+) nombre mostrado en la barra lateral
  perfil_riesgo  VARCHAR(20) CONSTRAINT ck_perfil CHECK (perfil_riesgo IN ('CONSERVADOR','MODERADO','AGRESIVO')),
  plan           VARCHAR(20),                                   -- (+) plan contratado (mockup de pago)
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. empresas (HU-01, HU-02, HU-04, HU-10). El índice NASDAQ 100 es una fila más ('^NDX').
CREATE TABLE empresas (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticker         VARCHAR(10)  NOT NULL UNIQUE,
  nombre_empresa VARCHAR(100) NOT NULL,
  sector         VARCHAR(50),
  es_indice      BOOLEAN NOT NULL DEFAULT FALSE,                -- (+)
  activa         BOOLEAN NOT NULL DEFAULT TRUE
);

-- 3. precios_historicos — hypertable (HU-02, RNF-02)
CREATE TABLE precios_historicos (
  time            TIMESTAMPTZ NOT NULL,
  empresa_id      BIGINT NOT NULL REFERENCES empresas(id),
  precio_apertura NUMERIC(12,4),
  precio_maximo   NUMERIC(12,4),
  precio_minimo   NUMERIC(12,4),
  precio_cierre   NUMERIC(12,4) NOT NULL,
  volumen         BIGINT,
  fuente          VARCHAR(20),                                  -- (+) procedencia: SIMULADO | ALPHAVANTAGE | COTIZACION_VIVO
  fecha_ingesta   TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,        -- (+) cuándo se almacenó (linaje del dato)
  PRIMARY KEY (time, empresa_id)                                -- UNIQUE(time, empresa_id): sin duplicados (HU-02 CA-3)
);
SELECT create_hypertable('precios_historicos', 'time', chunk_time_interval => INTERVAL '30 days');
CREATE INDEX idx_precios_empresa_time ON precios_historicos (empresa_id, time DESC);   -- B-Tree compuesto (RNF-02)
-- (+) Compresión columnar de chunks con más de 90 días: ≈ 90 % menos disco y barridos completos más rápidos.
ALTER TABLE precios_historicos SET (timescaledb.compress, timescaledb.compress_segmentby = 'empresa_id',
                                    timescaledb.compress_orderby = 'time DESC');
SELECT add_compression_policy('precios_historicos', INTERVAL '90 days');

-- 4. metricas_empresa (HU-03, HU-10)
CREATE TABLE metricas_empresa (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id             BIGINT NOT NULL UNIQUE REFERENCES empresas(id),
  beta_alcista           NUMERIC(8,4),
  beta_bajista           NUMERIC(8,4),
  beta                   NUMERIC(8,4),                          -- (+) beta global
  correlacion            NUMERIC(8,4),                          -- (+)
  volatilidad            NUMERIC(8,4) NOT NULL,
  retorno_esperado       NUMERIC(8,4),                          -- CAPM: rf + β·(E[Rm] − rf)
  rendimiento_dividendos NUMERIC(8,4),
  fecha_actualizacion    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_metricas_filtro ON metricas_empresa (volatilidad, beta_alcista, beta_bajista);   -- HU-09, HU-10

-- 5. listas_seguimiento (HU-08) — watchlist + portafolio teórico
CREATE TABLE listas_seguimiento (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id     BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  empresa_id     BIGINT NOT NULL REFERENCES empresas(id),
  cantidad       INTEGER NOT NULL DEFAULT 0 CONSTRAINT ck_cantidad CHECK (cantidad >= 0),   -- (+)
  favorito       BOOLEAN NOT NULL DEFAULT FALSE,                -- (+)
  fecha_agregado TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_lista_usuario_empresa UNIQUE (usuario_id, empresa_id)   -- HU-08 CA-4
);

-- 6. reglas_alertas (HU-06)
CREATE TABLE reglas_alertas (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id      BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  empresa_id      BIGINT NOT NULL REFERENCES empresas(id),
  tipo_condicion  VARCHAR(30) NOT NULL CONSTRAINT ck_tipo CHECK (tipo_condicion IN ('VARIACION_PORCENTUAL','PRECIO_LIMITE')),
  umbral          NUMERIC(12,4) NOT NULL CONSTRAINT ck_umbral CHECK (umbral > 0),  -- 12,4: admite precios del índice
  canal           VARCHAR(10) NOT NULL DEFAULT 'CORREO' CONSTRAINT ck_canal CHECK (canal IN ('CORREO','PUSH')),  -- (+)
  estado          VARCHAR(20) NOT NULL DEFAULT 'ACTIVA' CONSTRAINT ck_estado CHECK (estado IN ('ACTIVA','DISPARADA','INACTIVA')),
  pendiente_envio BOOLEAN NOT NULL DEFAULT FALSE,               -- (+) reintento si falla el correo (HU-06 CA-4)
  fecha_creacion  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 7. simulaciones_portafolio (HU-05)
CREATE TABLE simulaciones_portafolio (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id      BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  empresa_id      BIGINT NOT NULL REFERENCES empresas(id),
  monto_inicial   NUMERIC(12,2) NOT NULL CONSTRAINT ck_monto CHECK (monto_inicial > 0),   -- HU-05 CA-4
  fecha_inicio    DATE NOT NULL,
  fecha_fin       DATE NOT NULL,
  valor_final     NUMERIC(12,2) NOT NULL,
  fecha_ejecucion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_fechas CHECK (fecha_fin > fecha_inicio)
);

-- 8. (+) notificaciones enviadas por el worker de alertas (HU-06 CA-2)
CREATE TABLE notificaciones (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  regla_id   BIGINT REFERENCES reglas_alertas(id) ON DELETE SET NULL,
  texto      VARCHAR(255) NOT NULL,
  canal      VARCHAR(10) NOT NULL,
  estado_envio VARCHAR(20),                                     -- ENVIADO_CORREO | EN_APP
  proveedor_id VARCHAR(100),                                    -- X-Message-Id de SendGrid (rastreo de entrega)
  fecha      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_notificaciones_usuario_id ON notificaciones (usuario_id);

-- 9. (+) auditoria — copia consultable del log JSON (RNF-04), retención 90 días
CREATE TABLE auditoria (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
  email      VARCHAR(255),
  ip         VARCHAR(45),
  evento     VARCHAR(40) NOT NULL,
  estado     VARCHAR(10) NOT NULL,
  detalle    VARCHAR(255)
);
CREATE INDEX ix_auditoria_ts ON auditoria (ts);
CREATE INDEX ix_auditoria_usuario_id ON auditoria (usuario_id);

-- 10. (+) llamadas_externas — traza de cada llamada a Alpha Vantage y SendGrid (sin secretos), retención 90 días
CREATE TABLE llamadas_externas (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  proveedor   VARCHAR(20) NOT NULL,
  operacion   VARCHAR(40) NOT NULL,
  exito       BOOLEAN NOT NULL,
  http_status INTEGER,
  latencia_ms INTEGER NOT NULL,
  detalle     VARCHAR(255)
);
CREATE INDEX ix_llamadas_proveedor_ts ON llamadas_externas (proveedor, ts);
